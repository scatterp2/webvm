import { writable } from 'svelte/store';
import { browser } from '$app/environment'

let authKey = undefined;
let controlUrl = undefined;
if(browser)
{
	let params = new URLSearchParams("?"+window.location.hash.substr(1));
	authKey = params.get("authKey") || undefined;
	controlUrl = params.get("controlUrl") || undefined;
}
let dashboardUrl = controlUrl ? null : "https://login.tailscale.com/admin/machines";
let resolveLogin = null;
let rejectLogin = null;
let loginPromise = null;
let connectionState = writable("DISCONNECTED");
let exitNode = writable(false);
const kaggleTcpLink = writable(null);
let attachedDataDevice = null;
let currentKaggleTcpLink = null;

function writeKaggleProxyFile(link) {
	if (!attachedDataDevice)
		return;
	let source;
	if (link && link.ip) {
		const proxy = "socks5h://" + link.ip + ":8888";
		source = [
			"# Auto-generated by WebVM when the Kaggle TCP peer is online.",
			"if [ -n \"${WEBVM_KAGGLE_TCP_LINK_PROXY:-}\" ]; then",
			"  [ \"${ALL_PROXY:-}\" = \"$WEBVM_KAGGLE_TCP_LINK_PROXY\" ] && unset ALL_PROXY",
			"  [ \"${all_proxy:-}\" = \"$WEBVM_KAGGLE_TCP_LINK_PROXY\" ] && unset all_proxy",
			"  [ \"${HTTP_PROXY:-}\" = \"$WEBVM_KAGGLE_TCP_LINK_PROXY\" ] && unset HTTP_PROXY",
			"  [ \"${HTTPS_PROXY:-}\" = \"$WEBVM_KAGGLE_TCP_LINK_PROXY\" ] && unset HTTPS_PROXY",
			"  [ \"${http_proxy:-}\" = \"$WEBVM_KAGGLE_TCP_LINK_PROXY\" ] && unset http_proxy",
			"  [ \"${https_proxy:-}\" = \"$WEBVM_KAGGLE_TCP_LINK_PROXY\" ] && unset https_proxy",
			"fi",
			"export WEBVM_KAGGLE_TCP_LINK_IP=\"" + link.ip + "\"",
			"export WEBVM_KAGGLE_TCP_LINK_PROXY=\"" + proxy + "\"",
			"[ -n \"${ALL_PROXY:-}\" ] || export ALL_PROXY=\"$WEBVM_KAGGLE_TCP_LINK_PROXY\"",
			"[ -n \"${all_proxy:-}\" ] || export all_proxy=\"$WEBVM_KAGGLE_TCP_LINK_PROXY\"",
			"[ -n \"${HTTP_PROXY:-}\" ] || export HTTP_PROXY=\"$WEBVM_KAGGLE_TCP_LINK_PROXY\"",
			"[ -n \"${HTTPS_PROXY:-}\" ] || export HTTPS_PROXY=\"$WEBVM_KAGGLE_TCP_LINK_PROXY\"",
			"[ -n \"${http_proxy:-}\" ] || export http_proxy=\"$WEBVM_KAGGLE_TCP_LINK_PROXY\"",
			"[ -n \"${https_proxy:-}\" ] || export https_proxy=\"$WEBVM_KAGGLE_TCP_LINK_PROXY\"",
			"export NO_PROXY=\"localhost,127.0.0.1,::1\"",
			"export no_proxy=\"$NO_PROXY\"",
			""
		].join("\\n");
	} else {
		source = [
			"# Kaggle TCP peer is offline; remove only the proxy this feature set.",
			"if [ -n \"${WEBVM_KAGGLE_TCP_LINK_PROXY:-}\" ]; then",
			"  [ \"${ALL_PROXY:-}\" = \"$WEBVM_KAGGLE_TCP_LINK_PROXY\" ] && unset ALL_PROXY",
			"  [ \"${all_proxy:-}\" = \"$WEBVM_KAGGLE_TCP_LINK_PROXY\" ] && unset all_proxy",
			"  [ \"${HTTP_PROXY:-}\" = \"$WEBVM_KAGGLE_TCP_LINK_PROXY\" ] && unset HTTP_PROXY",
			"  [ \"${HTTPS_PROXY:-}\" = \"$WEBVM_KAGGLE_TCP_LINK_PROXY\" ] && unset HTTPS_PROXY",
			"  [ \"${http_proxy:-}\" = \"$WEBVM_KAGGLE_TCP_LINK_PROXY\" ] && unset http_proxy",
			"  [ \"${https_proxy:-}\" = \"$WEBVM_KAGGLE_TCP_LINK_PROXY\" ] && unset https_proxy",
			"fi",
			"unset WEBVM_KAGGLE_TCP_LINK_IP WEBVM_KAGGLE_TCP_LINK_PROXY",
			""
		].join("\\n");
	}
	attachedDataDevice.writeFile("/kaggle-tcp-link.env", source).catch((error) => {
		console.warn("[WebVM] Could not update Kaggle TCP proxy settings in /data.", error);
	});
}

export function attachDataDevice(device) {
	attachedDataDevice = device;
	writeKaggleProxyFile(currentKaggleTcpLink);
}

function resetLoginPromise()
{
	loginPromise = new Promise((f,r) => {
		resolveLogin = f;
		rejectLogin = r;
	});
}

function validateLoginUrl(url)
{
	const parsedUrl = new URL(url);
	if(parsedUrl.protocol != "https:" && parsedUrl.protocol != "http:")
		throw new Error("Invalid Tailscale login URL scheme");
	return parsedUrl.href;
}

function loginUrlCb(url)
{
	try
	{
		url = validateLoginUrl(url);
	}
	catch(e)
	{
		connectionState.set("LOGINFAILED");
		rejectLogin(e);
		resetLoginPromise();
		return;
	}
	connectionState.set("LOGINREADY");
	resolveLogin(url);
}

function stateUpdateCb(state)
{
	switch(state)
	{
		case 6 /*Running*/:
		{
			connectionState.set("CONNECTED");
			break;
		}
	}
}

function netmapUpdateCb(map)
{
	networkData.currentIp = map.self.addresses[0];
	var exitNodeFound = false;
	for(var i=0; i < map.peers.length;i++)
	{
		if(map.peers[i].exitNode)
		{
			exitNodeFound = true;
			break;
		}
	}
	exitNode.set(exitNodeFound);

	const peers = Array.isArray(map.peers) ? map.peers : [];
	const kagglePeer = peers.find((peer) => {
		const name = String(peer.name || peer.hostName || peer.dnsName || "")
			.toLowerCase().replace(/\.$/, "");
		return name.split(".")[0] === "webvm-kaggle-tcp-link";
	});
	let link = null;
	if (kagglePeer) {
		const addresses = Array.isArray(kagglePeer.addresses) ? kagglePeer.addresses : [];
		const ip = addresses.map((address) => String(address).split("/")[0])
			.find((address) => /^100\.\d{1,3}\.\d{1,3}\.\d{1,3}$/.test(address));
		if (ip)
			link = { ip, port: 8888, hostname: String(kagglePeer.name || "webvm-kaggle-tcp-link") };
	}
	currentKaggleTcpLink = link;
	kaggleTcpLink.set(link);
	writeKaggleProxyFile(link);
}

export async function startLogin()
{
	connectionState.set("LOGINSTARTING");
	const url = await loginPromise;
	networkData.loginUrl = url;
	return url;
}

async function handleCopyIP(event)
{
	// To prevent the default contexmenu from showing up when right-clicking..
	event.preventDefault();
	// Copy the IP to the clipboard.
	try
	{
		await window.navigator.clipboard.writeText(networkData.currentIp)
		connectionState.set("IPCOPIED");
		setTimeout(() => {
			connectionState.set("CONNECTED");
		}, 2000);
	}
	catch(msg)
	{
		console.log("Copy ip to clipboard: Error: " + msg);
	}
}

export function updateButtonData(state, handleConnect) {
	switch(state) {
		case "DISCONNECTED":
			return {
				buttonText: "Connect to Tailscale",
				isClickable: true,
				clickHandler: handleConnect,
				clickUrl: null,
				buttonTooltip: null,
				rightClickHandler: null
			};
		case "DOWNLOADING":
			return {
				buttonText: "Loading IP stack...",
				isClickable: false,
				clickHandler: null,
				clickUrl: null,
				buttonTooltip: null,
				rightClickHandler: null
			};
		case "LOGINSTARTING":
			return {
				buttonText: "Starting Login...",
				isClickable: false,
				clickHandler: null,
				clickUrl: null,
				buttonTooltip: null,
				rightClickHandler: null
			};
		case "LOGINREADY":
			return {
				buttonText: "Login to Tailscale",
				isClickable: true,
				clickHandler: null,
				clickUrl: networkData.loginUrl,
				buttonTooltip: null,
				rightClickHandler: null
			};
		case "LOGINFAILED":
			return {
				buttonText: "Invalid login URL",
				isClickable: false,
				clickHandler: null,
				clickUrl: null,
				buttonTooltip: null,
				rightClickHandler: null
			};
		case "CONNECTED":
			return {
				buttonText: `IP: ${networkData.currentIp}`,
				isClickable: true,
				clickHandler: null,
				clickUrl: networkData.dashboardUrl,
				buttonTooltip: "Right-click to copy",
				rightClickHandler: handleCopyIP
			};
		case "IPCOPIED":
			return {
				buttonText: "Copied!",
				isClickable: false,
				clickHandler: null,
				clickUrl: null,
				buttonTooltip: null,
				rightClickHandler: null
			};
		default:
			return {
				buttonText: `Text for state: ${state}`,
				isClickable: false,
				clickHandler: null,
				clickUrl: null,
				buttonTooltip: null,
				rightClickHandler: null
			};
	}
}

export const networkInterface = { authKey: authKey, controlUrl: controlUrl, loginUrlCb: loginUrlCb, stateUpdateCb: stateUpdateCb, netmapUpdateCb: netmapUpdateCb };

export const networkData = { currentIp: null, connectionState: connectionState, exitNode: exitNode, kaggleTcpLink: kaggleTcpLink, loginUrl: null, dashboardUrl: dashboardUrl }

resetLoginPromise();
