function writeKaggleProxyFile(link) {
	if (!attachedDataDevice)
		return;
	let source;
	if (link && link.ip) {
		const socksProxy = "socks5h://" + link.ip + ":" + link.port;
		const httpProxy = "http://" + link.ip + ":" + link.port;
		source = [
			"# Auto-generated by WebVM when the Kaggle TCP peer is online.",
			"if [ -n \"${WEBVM_KAGGLE_TCP_LINK_SOCKS_PROXY:-}\" ]; then",
			"  [ \"${ALL_PROXY:-}\" = \"$WEBVM_KAGGLE_TCP_LINK_SOCKS_PROXY\" ] && unset ALL_PROXY",
			"  [ \"${all_proxy:-}\" = \"$WEBVM_KAGGLE_TCP_LINK_SOCKS_PROXY\" ] && unset all_proxy",
			"fi",
			"if [ -n \"${WEBVM_KAGGLE_TCP_LINK_HTTP_PROXY:-}\" ]; then",
			"  [ \"${HTTP_PROXY:-}\" = \"$WEBVM_KAGGLE_TCP_LINK_HTTP_PROXY\" ] && unset HTTP_PROXY",
			"  [ \"${HTTPS_PROXY:-}\" = \"$WEBVM_KAGGLE_TCP_LINK_HTTP_PROXY\" ] && unset HTTPS_PROXY",
			"  [ \"${http_proxy:-}\" = \"$WEBVM_KAGGLE_TCP_LINK_HTTP_PROXY\" ] && unset http_proxy",
			"  [ \"${https_proxy:-}\" = \"$WEBVM_KAGGLE_TCP_LINK_HTTP_PROXY\" ] && unset https_proxy",
			"fi",
			"export WEBVM_KAGGLE_TCP_LINK_IP=\"" + link.ip + "\"",
			"export WEBVM_KAGGLE_TCP_LINK_SOCKS_PROXY=\"" + socksProxy + "\"",
			"export WEBVM_KAGGLE_TCP_LINK_HTTP_PROXY=\"" + httpProxy + "\"",
			"[ -n \"${ALL_PROXY:-}\" ] || export ALL_PROXY=\"$WEBVM_KAGGLE_TCP_LINK_SOCKS_PROXY\"",
			"[ -n \"${all_proxy:-}\" ] || export all_proxy=\"$WEBVM_KAGGLE_TCP_LINK_SOCKS_PROXY\"",
			"[ -n \"${HTTP_PROXY:-}\" ] || export HTTP_PROXY=\"$WEBVM_KAGGLE_TCP_LINK_HTTP_PROXY\"",
			"[ -n \"${HTTPS_PROXY:-}\" ] || export HTTPS_PROXY=\"$WEBVM_KAGGLE_TCP_LINK_HTTP_PROXY\"",
			"[ -n \"${http_proxy:-}\" ] || export http_proxy=\"$WEBVM_KAGGLE_TCP_LINK_HTTP_PROXY\"",
			"[ -n \"${https_proxy:-}\" ] || export https_proxy=\"$WEBVM_KAGGLE_TCP_LINK_HTTP_PROXY\"",
			"export NO_PROXY=\"localhost,127.0.0.1,::1\"",
			"export no_proxy=\"$NO_PROXY\"",
			""
		].join("\n");
	} else {
		source = [
			"# Kaggle TCP peer is offline; remove only the proxies this feature set.",
			"if [ -n \"${WEBVM_KAGGLE_TCP_LINK_SOCKS_PROXY:-}\" ]; then",
			"  [ \"${ALL_PROXY:-}\" = \"$WEBVM_KAGGLE_TCP_LINK_SOCKS_PROXY\" ] && unset ALL_PROXY",
			"  [ \"${all_proxy:-}\" = \"$WEBVM_KAGGLE_TCP_LINK_SOCKS_PROXY\" ] && unset all_proxy",
			"fi",
			"if [ -n \"${WEBVM_KAGGLE_TCP_LINK_HTTP_PROXY:-}\" ]; then",
			"  [ \"${HTTP_PROXY:-}\" = \"$WEBVM_KAGGLE_TCP_LINK_HTTP_PROXY\" ] && unset HTTP_PROXY",
			"  [ \"${HTTPS_PROXY:-}\" = \"$WEBVM_KAGGLE_TCP_LINK_HTTP_PROXY\" ] && unset HTTPS_PROXY",
			"  [ \"${http_proxy:-}\" = \"$WEBVM_KAGGLE_TCP_LINK_HTTP_PROXY\" ] && unset http_proxy",
			"  [ \"${https_proxy:-}\" = \"$WEBVM_KAGGLE_TCP_LINK_HTTP_PROXY\" ] && unset https_proxy",
			"fi",
			"unset WEBVM_KAGGLE_TCP_LINK_IP WEBVM_KAGGLE_TCP_LINK_SOCKS_PROXY WEBVM_KAGGLE_TCP_LINK_HTTP_PROXY",
			""
		].join("\n");
	}
	attachedDataDevice.writeFile("/kaggle-tcp-link.env", source).catch((error) => {
		console.warn("[WebVM] Could not update Kaggle TCP proxy settings in /data.", error);
	});
}

export function attachDataDevice(device) {
	attachedDataDevice = device;
	writeKaggleProxyFile(currentKaggleTcpLink);
}

function resetLoginPromise()
{
	loginPromise = new Promise((f,r) => {
		resolveLogin = f;
		rejectLogin = r;
	});
}

function validateLoginUrl(url)
{
	const parsedUrl = new URL(url);
	if(parsedUrl.protocol != "https:" && parsedUrl.protocol != "http:")
		throw new Error("Invalid Tailscale login URL scheme");
	return parsedUrl.href;
}

function loginUrlCb(url)
{
	try
	{
		url = validateLoginUrl(url);
	}
	catch(e)
	{
		connectionState.set("LOGINFAILED");
		rejectLogin(e);
		resetLoginPromise();
		return;
	}
	connectionState.set("LOGINREADY");
	resolveLogin(url);
}

function stateUpdateCb(state)
{
	switch(state)
	{
		case 6 /*Running*/:
		{
			connectionState.set("CONNECTED");
			break;
		}
	}
}

function netmapUpdateCb(map)
{
	networkData.currentIp = map.self.addresses[0];
	currentIpStore.set(networkData.currentIp);
	// The netmap carries the node's MagicDNS name, e.g.
	// "js-2.tailf987e.ts.net".  Strip the trailing dot.
	const dnsName = (map.self.dnsName || map.self.DNSName || map.self.name || "");
	currentDnsNameStore.set(String(dnsName).replace(/\.$/, "") || null);
	const peers = Array.isArray(map.peers) ? map.peers : [];

	const exitNodePeer = peers.find((peer) => peer.exitNode);
	if (exitNodePeer) {
		selectedExitNodePeer = exitNodePeer;
		exitNode.set(true);
	} else if (selectedExitNodePeer) {
		// The selected exit node stays usable after the control plane stops
		// reporting its exitNode flag. Only clear the indicator when the peer
		// is no longer present or has gone offline.
		const stillOnline = peers.some((peer) => {
			if (!peer.online)
				return false;
			if (peer.name && peer.name === selectedExitNodePeer.name)
				return true;
			const peerAddress = Array.isArray(peer.addresses) ? peer.addresses[0] : null;
			const selectedAddress = Array.isArray(selectedExitNodePeer.addresses)
				? selectedExitNodePeer.addresses[0]
				: null;
			return peerAddress && selectedAddress && peerAddress === selectedAddress;
		});
		if (!stillOnline) {
			selectedExitNodePeer = null;
			exitNode.set(false);
		}
	}

	const kagglePeer = peers.find((peer) => {
		const name = String(peer.name || peer.hostName || peer.dnsName || "")
			.toLowerCase().replace(/\.$/, "");
		return name.split(".")[0] === "webvm-kaggle-tcp-link";
	});
	let link = null;
	if (kagglePeer) {
		const addresses = Array.isArray(kagglePeer.addresses) ? kagglePeer.addresses : [];
		const ip = addresses.map((address) => String(address).split("/")[0])
			.find((address) => /^100\.\d{1,3}\.\d{1,3}\.\d{1,3}$/.test(address));
		if (ip)
			link = { ip, port: 18088, hostname: String(kagglePeer.name || "webvm-kaggle-tcp-link") };
	}
	currentKaggleTcpLink = link;
	kaggleTcpLink.set(link);
	writeKaggleProxyFile(link);
}

export async function startLogin()
{
	connectionState.set("LOGINSTARTING");
	const url = await loginPromise;
	networkData.loginUrl = url;
	return url;
}

async function handleCopyIP(event)
{
	// To prevent the default contexmenu from showing up when right-clicking..
	event.preventDefault();
	// Copy the IP to the clipboard.
	try
	{
		await window.navigator.clipboard.writeText(networkData.currentIp)
		connectionState.set("IPCOPIED");
		setTimeout(() => {
			connectionState.set("CONNECTED");
		}, 2000);
	}
	catch(msg)
	{
		console.log("Copy ip to clipboard: Error: " + msg);
	}
}

export function updateButtonData(state, handleConnect) {
	switch(state) {
		case "DISCONNECTED":
			return {
				buttonText: "Connect to Tailscale",
				isClickable: true,
				clickHandler: handleConnect,
				clickUrl: null,
				buttonTooltip: null,
				rightClickHandler: null
			};
		case "DOWNLOADING":
			return {
				buttonText: "Loading IP stack...",
				isClickable: false,
				clickHandler: null,
				clickUrl: null,
				buttonTooltip: null,
				rightClickHandler: null
			};
		case "LOGINSTARTING":
			return {
				buttonText: "Starting Login...",
				isClickable: false,
				clickHandler: null,
				clickUrl: null,
				buttonTooltip: null,
				rightClickHandler: null
			};
		case "LOGINREADY":
			return {
				buttonText: "Login to Tailscale",
				isClickable: true,
				clickHandler: null,
				clickUrl: networkData.loginUrl,
				buttonTooltip: null,
				rightClickHandler: null
			};
		case "LOGINFAILED":
			return {
				buttonText: "Invalid login URL",
				isClickable: false,
				clickHandler: null,
				clickUrl: null,
				buttonTooltip: null,
				rightClickHandler: null
			};
		case "CONNECTED":
			return {
				buttonText: `IP: ${networkData.currentIp}`,
				isClickable: true,
				clickHandler: null,
				clickUrl: networkData.dashboardUrl,
				buttonTooltip: "Right-click to copy",
				rightClickHandler: handleCopyIP
			};
		case "IPCOPIED":
			return {
				buttonText: "Copied!",
				isClickable: false,
				clickHandler: null,
				clickUrl: null,
				buttonTooltip: null,
				rightClickHandler: null
			};
		default:
			return {
				buttonText: `Text for state: ${state}`,
				isClickable: false,
				clickHandler: null,
				clickUrl: null,
				buttonTooltip: null,
				rightClickHandler: null
			};
	}
}

